### 基本データ、加工データ、実績データの読込み
# Maskデータ
mask_df = pd.read_csv('./mask_trial_outputs/clinical_case_mask.csv')
# 加工データ
# # -------------------------------------------------------
tmp01_df = mask_df[['PMCID','PMID','Case #','masked_token_count']]
# # -------------------------------------------------------
ct0,ct1,ct2,ct3,ct4,ct5,ct6,ct7 = [],[],[],[],[],[],[],[]
for k in range (len(mask_df)):
    mask_type = mask_df['mask_types'][k]
    ct0.append(mask_type.count('AGE'))
    ct1.append(mask_type.count('DATE'))
    ct2.append(mask_type.count('ID'))
    ct3.append(mask_type.count('LOCATION'))
    ct4.append(mask_type.count('LOW_RISK_WORDING'))
    ct5.append(mask_type.count('NAME'))
    ct6.append(mask_type.count('ORGANIZATION'))
    ct7.append(mask_type.count('SEX'))
# # -------------------------------------------------------
tmp01_df['AGE'] = ct0
tmp01_df['DATE'] = ct1
tmp01_df['ID'] = ct2
tmp01_df['LOCATION'] = ct3
tmp01_df['LOW_RISK_WORDING'] = ct4
tmp01_df['NAME'] = ct5
tmp01_df['ORGANIZATION'] = ct6
tmp01_df['SEX'] = ct7
# # -------------------------------------------------------
ct8,ct9,cta = [],[],[]
for k in range (len(mask_df)):
    masked_token = mask_df['masked_tokens'][k]
    ct8.append(masked_token.count('Lassa'))
    ct9.append(masked_token.count('Hanta'))
    cta.append(masked_token.count('Puumala'))
# # -------------------------------------------------------
tmp01_df['Lassa'] = ct8
tmp01_df['Hanta'] = ct9
tmp01_df['Puumala'] = cta
# # -------------------------------------------------------
# CSVファイルに保存
tmp01_df.to_csv("./mask_trial_outputs/clinical_case_mask_ana01.csv", index=False) # index=Falseで行番号を除外
